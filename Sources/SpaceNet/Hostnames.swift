import Foundation
import SpaceCore

/// Local hostnames under *.space.test, using third-party tools only:
/// - dnsmasq answers *.space.test → 127.0.0.1 on 127.0.0.1:53535 (macOS asks it via /etc/resolver/space.test)
/// - Caddy reverse-proxies each site to its localhost port over HTTP and HTTPS (local CA)
/// Space just writes their config files and keeps both running as child processes.
public actor Hostnames {
    public static let domain = "space.test"
    static let dnsPort = 53535
    static let caddyAdmin = "localhost:20190"

    private var state: SpaceState
    private var trusted = false
    private var caddy: Process?
    private var dnsmasq: Process?

    let caddyBin = ProcessRunner.locate(["/opt/homebrew/bin/caddy", "/usr/local/bin/caddy"])
    let dnsmasqBin = ProcessRunner.locate(["/opt/homebrew/sbin/dnsmasq", "/usr/local/sbin/dnsmasq"])

    static var caddyfile: URL { SpacePaths.root.appending(path: "Caddyfile") }
    static var dnsmasqConf: URL { SpacePaths.root.appending(path: "dnsmasq.conf") }
    static var resolverFile: String { "/etc/resolver/\(domain)" }
    /// Caddy keeps its local CA here (default data dir on macOS).
    static var caRoot: URL {
        FileManager.default.homeDirectoryForCurrentUser
            .appending(path: "Library/Application Support/Caddy/pki/authorities/local/root.crt")
    }

    public init() { state = SpaceState.load() }

    // MARK: Lifecycle

    /// Writes configs and (re)starts dnsmasq and Caddy if installed.
    public func start() async throws {
        try SpacePaths.ensure()
        try writeConfigs()
        if caddy == nil && dnsmasq == nil { await killLeftovers() }
        if let dnsmasqBin, dnsmasq?.isRunning != true {
            dnsmasq = try launch(dnsmasqBin.string, ["--keep-in-foreground", "--conf-file=\(Self.dnsmasqConf.path)"], log: "dnsmasq.log")
        }
        if let caddyBin, caddy?.isRunning != true {
            // --watch reloads automatically whenever we rewrite the Caddyfile.
            caddy = try launch(caddyBin.string, ["run", "--config", Self.caddyfile.path, "--adapter", "caddyfile", "--watch"], log: "caddy.log")
        }
    }

    /// Copies left behind by a previous spaced (e.g. killed during an update) would hold the ports.
    private func killLeftovers() async {
        _ = try? await ProcessRunner.run("/usr/bin/pkill", ["-f", "dnsmasq.*--conf-file=\(Self.dnsmasqConf.path)"])
        _ = try? await ProcessRunner.run("/usr/bin/pkill", ["-f", "caddy run --config \(Self.caddyfile.path)"])
        try? await Task.sleep(for: .milliseconds(300))
    }

    public func stop() {
        caddy?.terminate(); dnsmasq?.terminate()
        caddy = nil; dnsmasq = nil
    }

    private func launch(_ path: String, _ args: [String], log: String) throws -> Process {
        let p = Process()
        p.executableURL = URL(fileURLWithPath: path)
        p.arguments = args
        let logURL = SpacePaths.root.appending(path: log)
        FileManager.default.createFile(atPath: logURL.path, contents: nil)
        let handle = try FileHandle(forWritingTo: logURL)
        handle.seekToEndOfFile()
        p.standardOutput = handle
        p.standardError = handle
        try p.run()
        return p
    }

    // MARK: Config

    static func dnsmasqConfig() -> String {
        """
        # Generated by Space. Answers *.\(domain) with this Mac; nothing else.
        port=\(dnsPort)
        listen-address=127.0.0.1
        bind-interfaces
        no-resolv
        no-hosts
        address=/\(domain)/127.0.0.1
        address=/\(domain)/::1

        """
    }

    static func caddyConfig(sites: [SpaceState.Site]) -> String {
        var out = """
        # Generated by Space — edit sites from the Space app or `spaced hosts`.
        {
        \tadmin \(caddyAdmin)
        \tlocal_certs
        \tskip_install_trust
        }

        """
        for site in sites.sorted(by: { $0.name < $1.name }) {
            let host = "\(site.name).\(domain)"
            // Listing both schemes serves HTTP and HTTPS (no forced redirect).
            out += """

            http://\(host), https://\(host) {
            \treverse_proxy localhost:\(site.port)
            }

            """
        }
        return out
    }

    private func writeConfigs() throws {
        try Self.dnsmasqConfig().write(to: Self.dnsmasqConf, atomically: true, encoding: .utf8)
        try Self.caddyConfig(sites: state.sites).write(to: Self.caddyfile, atomically: true, encoding: .utf8)
    }

    // MARK: Sites

    static var namePattern: Regex<(Substring, Substring?, Substring?, Substring?)> { /^[a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?(\.[a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?)*$/ }

    public func addSite(name raw: String, port: Int) throws {
        let name = raw.lowercased().replacingOccurrences(of: ".\(Self.domain)", with: "")
        guard name.wholeMatch(of: Self.namePattern) != nil else { throw HostnameError.invalidName(raw) }
        guard (1...65535).contains(port), port != 80, port != 443 else { throw HostnameError.invalidPort(port) }
        state = SpaceState.load()
        state.sites.removeAll { $0.name == name }
        state.sites.append(.init(name: name, port: port))
        try state.save()
        try writeConfigs()
    }

    public func removeSite(_ name: String) throws {
        state = SpaceState.load()
        state.sites.removeAll { $0.name == name }
        try state.save()
        try writeConfigs()
    }

    // MARK: Status

    public func status() async -> HostsStatus {
        state = SpaceState.load()
        let used = Set(state.sites.map(\.port))
        let suggested = (3000..<4000).first { !used.contains($0) && Sockets.isFree(port: $0) } ?? 3000
        let sites = state.sites.sorted { $0.name < $1.name }.map { s in
            let host = "\(s.name).\(Self.domain)"
            return HostsStatus.SiteView(name: s.name, host: host, port: s.port, up: !Sockets.isFree(port: s.port) || Self.canConnect(s.port),
                                        urls: ["https://\(host)", "http://\(host)"])
        }
        return HostsStatus(
            domain: Self.domain,
            caddyInstalled: caddyBin != nil,
            dnsmasqInstalled: dnsmasqBin != nil,
            resolverInstalled: Self.resolverInstalled(),
            certificateTrusted: await isTrusted(),
            proxyRunning: caddy?.isRunning == true,
            dnsRunning: dnsmasq?.isRunning == true,
            sites: sites,
            suggestedPort: suggested
        )
    }

    static func canConnect(_ port: Int) -> Bool {
        guard let fd = try? Sockets.connect(port: port) else { return false }
        close(fd)
        return true
    }

    static func resolverInstalled() -> Bool {
        guard let text = try? String(contentsOfFile: resolverFile, encoding: .utf8) else { return false }
        return text.contains("127.0.0.1") && text.contains("\(dnsPort)")
    }

    /// Cached once true — trust doesn't go away by itself, and checking spawns `security`.
    private func isTrusted() async -> Bool {
        if !trusted { trusted = await Self.certificateTrusted() }
        return trusted
    }

    static func certificateTrusted() async -> Bool {
        guard FileManager.default.fileExists(atPath: caRoot.path) else { return false }
        let r = try? await ProcessRunner.run("/usr/bin/security", ["verify-cert", "-c", caRoot.path, "-p", "ssl", "-q"])
        return r?.ok == true
    }

    /// One-time setup: the resolver file needs admin rights; the certificate is trusted by the caller as the user.
    public func setup() async -> SetupScript {
        var script = ""
        if !Self.resolverInstalled() {
            script = "mkdir -p /etc/resolver && printf 'nameserver 127.0.0.1\\nport \(Self.dnsPort)\\n' > \(Self.resolverFile)"
        }
        let caExists = FileManager.default.fileExists(atPath: Self.caRoot.path)
        let alreadyTrusted = await Self.certificateTrusted()
        let needsTrust = caExists && !alreadyTrusted
        return SetupScript(script: script, certificate: needsTrust ? Self.caRoot.path : nil)
    }

    /// Waits briefly for Caddy to create its local CA (it does so on first start).
    public func waitForCertificateAuthority(timeout: Duration = .seconds(10)) async {
        let deadline = ContinuousClock.now + timeout
        while ContinuousClock.now < deadline, !FileManager.default.fileExists(atPath: Self.caRoot.path) {
            try? await Task.sleep(for: .milliseconds(250))
        }
    }
}

public enum HostnameError: Error, CustomStringConvertible {
    case invalidName(String)
    case invalidPort(Int)
    public var description: String {
        switch self {
        case .invalidName(let n): "'\(n)' isn't a valid hostname (lowercase letters, digits, hyphens; dots for subdomains)"
        case .invalidPort(let p): "Port \(p) can't be used for a site"
        }
    }
}
